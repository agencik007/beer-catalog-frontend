/** Same keys as English; plural keys are checked separately (Polish has more forms). */
type Plain<T> = {
	[K in keyof T as K extends `${string}_${'one' | 'other'}` ? never : K]: T[K] extends string
		? string
		: Plain<T[K]>;
} & { [key: string]: unknown };
export type Messages = Plain<typeof en>;
